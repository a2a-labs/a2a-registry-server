import { readFile, unlink } from "node:fs/promises";

const npmIgnore = new URL("../ui/.npmignore", import.meta.url);
const marker = "# Generated by @a2a-labs/registry-server prepack; removed by postpack.\n";

try {
  if (await readFile(npmIgnore, "utf8") === marker) await unlink(npmIgnore);
} catch (error) {
  if (error.code !== "ENOENT") throw error;
}
