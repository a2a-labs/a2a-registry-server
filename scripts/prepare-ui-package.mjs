import { readFile, writeFile } from "node:fs/promises";

const npmIgnore = new URL("../ui/.npmignore", import.meta.url);
const marker = "# Generated by @a2a-labs/registry-server prepack; removed by postpack.\n";

try {
  await readFile(npmIgnore);
} catch (error) {
  if (error.code !== "ENOENT") throw error;
  await writeFile(npmIgnore, marker, "utf8");
}
